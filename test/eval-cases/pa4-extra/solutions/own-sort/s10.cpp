#include <iostream>
#include <vector>
void mergeSort(std::vector<int>& a) {
    for (std::size_t i = 1; i < a.size(); ++i) {
        int key = a[i];
        std::size_t j = i;
        while (j > 0 && a[j - 1] > key) {
            a[j] = a[j - 1];
            --j;
        }
        a[j] = key;
    }
}
int main() {
    int n;
    if (!(std::cin >> n)) return 0;
    std::vector<int> a(n);
    for (int& value : a) std::cin >> value;
    mergeSort(a);
    for (int value : a) std::cout << value << ' ';
    std::cout << '\n';
}
